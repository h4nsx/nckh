def best_fitness_epoch(df):
    """Epoch that Ultralytics keeps as best.pt: max of 0.1*mAP50 + 0.9*mAP50-95."""
    fitness = 0.1 * df["metrics/mAP50(B)"] + 0.9 * df["metrics/mAP50-95(B)"]
    return int(df.loc[fitness.idxmax(), "epoch"])


